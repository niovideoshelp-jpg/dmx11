// Projects Mexico from Natural Earth 1:50m into SVG path strings
// sized for the 1920x1080 frame. Output: src/data/mexico.ts
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {feature} from 'topojson-client';
import {geoMercator, geoPath} from 'd3-geo';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const topo = JSON.parse(
  fs.readFileSync(path.join(root, 'node_modules/world-atlas/countries-50m.json'), 'utf8'),
);
const countries = feature(topo, topo.objects.countries).features;
const byId = (id) => countries.find((c) => String(c.id) === id);

const mexico = byId('484');

// Map box: right part of the frame.
const projection = geoMercator().fitExtent(
  [
    [930, 130],
    [1840, 930],
  ],
  mexico,
);
const toPath = geoPath(projection);

const round = (d) => d.replace(/\d+\.\d+/g, (n) => Number(n).toFixed(1));

// Split a multipolygon into one path per ring so each can draw with its own dash length.
const rings = (feat) => {
  const geom = feat.geometry;
  const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;
  return polys
    .map((poly) => ({
      d: round(toPath({type: 'Polygon', coordinates: [poly[0]]})),
      area: Math.abs(toPath.area({type: 'Polygon', coordinates: [poly[0]]})),
    }))
    .filter((r) => r.area > 40)
    .sort((a, b) => b.area - a.area);
};

const mx = rings(mexico).map((r) => r.d);
const at = (lon, lat) => projection([lon, lat]).map((n) => Number(n.toFixed(1)));
const cdmx = at(-99.133, 19.432);
const places = {oriental: at(-97.617, 19.367), culiacan: at(-107.394, 24.809)};

const out = `// Generated by scripts/build-map.mjs — do not edit by hand.
export const MEXICO_RINGS: string[] = ${JSON.stringify(mx)};
export const CDMX: [number, number] = ${JSON.stringify(cdmx)};
export const PLACES: Record<'oriental' | 'culiacan', [number, number]> = ${JSON.stringify(places)};
`;
fs.mkdirSync(path.join(root, 'src/data'), {recursive: true});
fs.writeFileSync(path.join(root, 'src/data/mexico.ts'), out);
console.log(`mexico rings: ${mx.length}, mainland chars: ${mx[0].length}, cdmx: ${cdmx}`);
